const { chromium } = require('playwright');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const base = process.env.ADAM_TEST_URL;
assert(base && new URL(base).hostname === '127.0.0.1');
const fixture = JSON.parse(process.env.ADAM_ADMIN_FIXTURE);
(async () => {
    const browser = await chromium.launch({ channel: 'msedge', headless: true });
    const errors = [];
    let checks = 0;
    const check = (value, message) => { assert(value, message); checks++; };
    const context = await browser.newContext({ viewport: { width: 1440, height: 1000 } });
    const page = await context.newPage();
    page.on('pageerror', e => errors.push(e.message));
    const out = path.resolve('.run-admin'); fs.mkdirSync(out, { recursive: true });
    async function login(ctx, email) {
        const p = await ctx.newPage();
        await p.goto(base + '/account/login');
        await p.locator('#Email').fill(email);
        await p.locator('#Password').fill(fixture.password);
        await Promise.all([p.waitForURL(url => !url.pathname.startsWith('/account/login')), p.locator('form button[type=submit]').click()]);
        return p;
    }
    async function change(action, reason = 'Проверка браузером') {
        await page.goto(base + '/admin/users/' + fixture.learnerId);
        await page.locator('#action').selectOption(action);
        await page.locator('#reason').fill(reason);
        await page.getByRole('button', { name: 'Проверить и подтвердить' }).click();
        await page.locator('dialog[open] [data-confirm]').click();
        await page.waitForLoadState('domcontentloaded');
        await page.locator('[role=status]').waitFor();
    }
    try {
        let response = await page.request.get(base + '/admin', { maxRedirects: 0 });
        check(response.status() === 302, 'Guest admin route');
        response = await page.request.post(base + '/admin/users/' + fixture.learnerId, { form: { Action: 'grant-admin' }, maxRedirects: 0 });
        check([302, 400].includes(response.status()), 'Guest mutation');
        await context.addCookies([{ name: 'Adam.Auth', value: 'legacy-ticket', url: base }]);
        response = await page.request.get(base + '/admin', { maxRedirects: 0 }); check(response.status() === 302, 'Old cookie accepted');
        const registrationContext = await browser.newContext(); const registrationPage = await registrationContext.newPage();
        await registrationPage.goto(base + '/account/register');
        await registrationPage.locator('#PublicName').fill('Проверка регистрации ӕ');
        await registrationPage.locator('#Email').fill('registration-' + require('node:crypto').randomUUID() + '@example.invalid');
        await registrationPage.locator('#Password').fill(require('node:crypto').randomBytes(8).toString('hex').slice(0, 8));
        await registrationPage.locator('form.stack-form').evaluate(form => { const input = document.createElement('input'); input.type = 'hidden'; input.name = 'IsEditor'; input.value = 'true'; form.append(input); });
        await Promise.all([registrationPage.waitForURL('**/profile/avatar?onboarding=true'), registrationPage.locator('form button[type=submit]').click()]);
        response = await registrationPage.request.get(base + '/admin', { maxRedirects: 0 }); check(response.status() === 302 && response.headers().location.includes('access-denied'), 'Registration granted Admin');
        response = await registrationPage.request.get(base + '/editor', { maxRedirects: 0 }); check(response.status() === 302 && response.headers().location.includes('access-denied'), 'Registration granted Editor');
        await registrationContext.close();
        const adminPage = await login(context, fixture.admin); await adminPage.close();
        response = await page.request.post(base + '/admin/users/' + fixture.learnerId, { form: { Action: 'grant-admin', Reason: 'Без CSRF' }, maxRedirects: 0 });
        check(response.status() === 400, 'Missing CSRF accepted');
        for (const route of ['/admin', '/admin?days=7', '/admin?days=90', '/admin/users', '/admin/materials', '/admin/audit']) {
            response = await page.goto(base + route); check(response.ok(), 'Admin route failed: ' + route);
            check((await page.locator('h1').textContent()).length > 0, 'Missing page heading');
        }
        response = await page.goto(base + '/editor'); check(response.ok(), 'Admin cannot edit');
        await page.goto(base + '/admin'); await page.screenshot({ path: path.join(out, 'overview-wide.png'), fullPage: true });
        await page.goto(base + '/admin/users');
        check(await page.locator('tbody tr').count() === 25, 'Pagination size');
        await page.getByRole('link', { name: 'Далее', exact: true }).click(); check(new URL(page.url()).searchParams.get('page') === '2', 'Next page link');
        await page.locator('#q').fill('НЕТ_ТАКОГО_ПОЛЬЗОВАТЕЛЯ'); await page.getByRole('button', { name: 'Найти', exact: true }).click();
        check(await page.locator('.empty').isVisible(), 'Empty search');
        await page.getByRole('button', { name: 'Очистить поиск' }).click(); await page.waitForLoadState('domcontentloaded');
        check(await page.locator('tbody tr').count() === 25, 'Clear search');
        const learnerContext = await browser.newContext(); const learnerPage = await login(learnerContext, fixture.learner);
        response = await learnerPage.request.get(base + '/admin', { maxRedirects: 0 }); check(response.status() === 302 && response.headers().location.includes('access-denied'), 'Learner sees admin');
        const editorContext = await browser.newContext(); const editorPage = await login(editorContext, fixture.legacy);
        response = await editorPage.request.get(base + '/admin', { maxRedirects: 0 }); check(response.status() === 302 && response.headers().location.includes('access-denied'), 'Editor sees admin');
        response = await editorPage.goto(base + '/editor'); check(response.ok(), 'Migrated Editor cannot edit');
        await change('grant-editor');
        response = await learnerPage.request.get(base + '/profile', { maxRedirects: 0 }); check(response.status() === 302 && response.headers().location.includes('login'), 'Grant did not invalidate session');
        await learnerPage.close(); const editorLearner = await login(learnerContext, fixture.learner);
        response = await editorLearner.goto(base + '/editor'); check(response.ok(), 'Granted Editor cannot edit');
        await change('revoke-editor');
        response = await editorLearner.request.get(base + '/editor', { maxRedirects: 0 }); check(response.status() === 302 && response.headers().location.includes('login'), 'Revoke did not invalidate session');
        await change('block');
        const blocked = await learnerContext.newPage(); await blocked.goto(base + '/account/login'); await blocked.locator('#Email').fill(fixture.learner); await blocked.locator('#Password').fill(fixture.password); await blocked.locator('form button[type=submit]').click();
        check(new URL(blocked.url()).pathname === '/account/login', 'Blocked login accepted');
        await change('unblock'); const restored = await login(learnerContext, fixture.learner); await restored.close();
        await change('signout');
        response = await editorLearner.request.get(base + '/profile', { maxRedirects: 0 }); check(response.status() === 302, 'Signout failed');
        await page.goto(base + '/admin/users/' + fixture.learnerId);
        await page.locator('#reason').fill('x'); await page.getByRole('button', { name: 'Проверить и подтвердить' }).click();
        check(await page.locator('[data-cancel]').evaluate(el => document.activeElement === el), 'Confirmation focus');
        await page.keyboard.press('Escape'); check(!(await page.locator('dialog').evaluate(el => el.open)), 'Escape confirmation');
        await page.getByRole('button', { name: 'Проверить и подтвердить' }).click(); await page.locator('[data-confirm]').click();
        await page.locator('.validation-summary-errors').waitFor(); check((await page.locator('#reason').inputValue()) === 'x', 'Validation lost input');
        await page.goto(base + '/admin/users/' + fixture.learnerId); await page.screenshot({ path: path.join(out, 'user-wide.png'), fullPage: true });
        await page.setViewportSize({ width: 390, height: 844 }); await page.goto(base + '/admin');
        check(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), 'Mobile overflow');
        await page.getByRole('button', { name: 'Разделы панели' }).click(); await page.getByRole('link', { name: 'Пользователи', exact: true }).click();
        check(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), 'Mobile table overflow');
        await page.screenshot({ path: path.join(out, 'users-mobile.png'), fullPage: true });
        await page.goto(base + '/admin/users/' + fixture.learnerId);
        check(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), 'Mobile user details overflow');
        await page.goto(base + '/admin'); await page.screenshot({ path: path.join(out, 'overview-mobile.png'), fullPage: true });
        await page.keyboard.press('Tab'); check(await page.evaluate(() => document.activeElement !== document.body), 'Keyboard focus');
        await page.emulateMedia({ reducedMotion: 'reduce' });
        check(await page.locator('.admin-brand').textContent().then(t => t.includes('Ӕ')), 'Ossetian letters');
        check(errors.length === 0, 'Browser runtime errors');
        console.log(`Admin browser: ${checks} checks passed.`);
        await learnerContext.close(); await editorContext.close();
    } finally { await browser.close(); }
})().catch(error => { console.error(error.message); process.exit(1); });
